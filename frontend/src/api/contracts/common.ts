/**
 * Shared wire aliases and enumerations, mirrored from the Java domain.
 *
 * The aliases are documentation the compiler carries: `Decimal` is a money
 * string in major units, `BusinessDate` is `YYYY-MM-DD` with no time or zone,
 * `Instant` is ISO-8601 with one. Treating the first two as numbers or Dates is
 * exactly the bug class this file exists to make visible.
 *
 * Every constant below was read out of the backend enums. Where a state is
 * shown to a user, the label sits beside it: the UI never prints a raw
 * SCREAMING_CASE token at someone.
 */

/** A v4 UUID as text. */
export type UUID = string

/** Money or a ratio, as a decimal string in major units: "39300.00". */
export type Decimal = string

/** A calendar date with no time and no zone: "2026-03-31". */
export type BusinessDate = string

/** A point in time with a zone: "2026-09-07T13:12:45.918Z". */
export type Instant = string

/** An integer discount in basis points. 12% is exactly 1200. */
export type BasisPoints = number

