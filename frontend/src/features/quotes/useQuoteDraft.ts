import { useCallback, useEffect, useMemo, useRef, useState } from 'react'

import {
  ApiError,
  quotes as quotesApi,
  type BackorderTerms,
  type QuoteDraftRequest,
  type QuoteEvaluation,
  type QuoteLineRequest,
  type UUID,
} from '@/api'

/**
 * The editable terms of a quotation, and their live valuation.
 *
 * This hook owns the one genuinely difficult interaction in the product: the
 * user is typing, the server is the only thing that knows what the numbers are,
 * and other people can change the same record while they type.
 *
 * The rules it implements, each of which exists because the alternative is a
 * real defect:
 *
 *  - **Evaluation is debounced and cancellable.** Every keystroke would be a
 *    round trip; worse, a slow early response could land after a fast later one
 *    and repaint the totals for terms the user has already moved past. Each
 *    evaluation aborts the one before it, and a response is only accepted if
 *    its request is still the newest.
 *  - **Editing never saves.** Leaving a field does not persist money. Save is a
 *    deliberate action, and it carries `expectedRowVersion` so a stale editor
 *    cannot overwrite someone else's change.
 *  - **A dirty form is never refreshed underneath.** When the server copy moves
 *    while there are unsaved edits, the local draft is kept and the caller is
 *    told, so it can offer compare / reload / reapply instead of silently
 *    discarding work.
 */

export interface DraftLine {
  /** Stable across revisions; generated by the server for genuinely new lines. */
  lineKey: string
  variantId: UUID | null
  planId: UUID | null
  /** Kept as the typed string so a half-typed "1." does not become NaN. */
  quantity: string
  lineDiscountBp: number | null
  promisedDate: string | null
  /** Read-only, from the last evaluation — for rendering while editing. */
  description?: string
  lineKind?: 'ONE_TIME' | 'RECURRING'
}

export interface DraftState {
  lines: DraftLine[]
  orderDiscountBp: number | null
  backorderTerms: BackorderTerms
  requestedActivationDate: string | null
}

/** Turns a server evaluation into an editable draft. */
function draftFrom(evaluation: QuoteEvaluation): DraftState {
  return {
    lines: evaluation.lines.map((line) => ({
      lineKey: line.lineKey,
      variantId: line.variantId,
      planId: line.planId,
      quantity: String(line.quantity),
      lineDiscountBp: line.lineDiscountBp,
      promisedDate: line.promisedDate,
      description: line.description,
      lineKind: line.lineKind,
    })),
    orderDiscountBp: evaluation.orderDiscountBp,
    backorderTerms: evaluation.backorderTerms,
    requestedActivationDate: evaluation.requestedActivationDate,
  }
}

/** The wire shape. Only identifiers, quantities and requested discounts. */
function toRequest(draft: DraftState, expectedRowVersion?: number): QuoteDraftRequest {
  const lines: QuoteLineRequest[] = draft.lines.map((line) => ({
    lineKey: line.lineKey,
    variantId: line.variantId,
    planId: line.planId,
    quantity: line.quantity,
    lineDiscountBp: line.lineDiscountBp ?? 0,
    promisedDate: line.promisedDate,
  }))
  return {
    lines,
    orderDiscountBp: draft.orderDiscountBp ?? 0,
    backorderTerms: draft.backorderTerms,
    requestedActivationDate: draft.requestedActivationDate,
    ...(expectedRowVersion === undefined ? {} : { expectedRowVersion }),
  }
}

/** True when the two describe different commercial terms. */
function differs(a: DraftState, b: DraftState): boolean {
  if (a.orderDiscountBp !== b.orderDiscountBp) return true
  if (a.backorderTerms !== b.backorderTerms) return true
  if (a.requestedActivationDate !== b.requestedActivationDate) return true
  if (a.lines.length !== b.lines.length) return true
  return a.lines.some((line, index) => {
    const other = b.lines[index]
    return (
      line.lineKey !== other.lineKey ||
      Number(line.quantity) !== Number(other.quantity) ||
      (line.lineDiscountBp ?? 0) !== (other.lineDiscountBp ?? 0) ||
      line.promisedDate !== other.promisedDate ||
      line.variantId !== other.variantId ||
      line.planId !== other.planId
    )
  })
}

const EVALUATION_DEBOUNCE_MS = 300

export interface UseQuoteDraft {
  draft: DraftState
  /** The figures on screen: the live evaluation while editing, else the server's. */
  evaluation: QuoteEvaluation
  dirty: boolean
  evaluating: boolean
  evaluationError: unknown
  /** Set when the server copy moved while there were unsaved edits. */
  externalChange: QuoteEvaluation | null
  setLines: (update: (lines: DraftLine[]) => DraftLine[]) => void
  setOrderDiscountBp: (bp: number | null) => void
  setBackorderTerms: (terms: BackorderTerms) => void
  setRequestedActivationDate: (date: string | null) => void
  /** Throws away local edits and takes the server's current terms. */
  reset: () => void
  /** Adopts the newer server version, discarding local edits. */
  acceptExternal: () => void
  /** Keeps local edits and dismisses the notice; the next save will conflict. */
  dismissExternal: () => void
  /** The body to send when saving. */
  saveRequest: () => QuoteDraftRequest
}

export function useQuoteDraft(server: QuoteEvaluation): UseQuoteDraft {
  const [draft, setDraft] = useState<DraftState>(() => draftFrom(server))
  const [live, setLive] = useState<QuoteEvaluation | null>(null)
  const [evaluating, setEvaluating] = useState(false)
  const [evaluationError, setEvaluationError] = useState<unknown>(null)
  const [externalChange, setExternalChange] = useState<QuoteEvaluation | null>(null)

  const baseline = useRef<DraftState>(draftFrom(server))
  const baselineRevision = useRef<string>(server.revisionId)
  const dirty = useMemo(() => differs(draft, baseline.current), [draft])

  // The reconciliation effect below has to know whether there are unsaved edits
  // *at the moment the server copy changes*, which is not the same question as
  // "re-run me when dirtiness changes". A ref answers the first question without
  // making the effect depend on the second.
  const dirtyRef = useRef(dirty)
  dirtyRef.current = dirty

  /* ------------------------------------------------ server copy changed */
  useEffect(() => {
    // Same version we are already editing against: nothing to reconcile.
    if (server.revisionId === baselineRevision.current && !server.preview) {
      baseline.current = draftFrom(server)
      return
    }
    if (server.revisionId === baselineRevision.current) return

    if (dirtyRef.current) {
      // Someone else moved the record while there are unsaved edits. Keep the
      // edits; the caller decides what to offer.
      setExternalChange(server)
      return
    }
    baselineRevision.current = server.revisionId
    baseline.current = draftFrom(server)
    setDraft(draftFrom(server))
    setLive(null)
    setExternalChange(null)
  }, [server])

  /* --------------------------------------------------------- evaluation */
  const inFlight = useRef<AbortController | null>(null)
  const sequence = useRef(0)

  useEffect(() => {
    if (!dirty) {
      setLive(null)
      setEvaluationError(null)
      return
    }

    const timer = window.setTimeout(() => {
      inFlight.current?.abort()
      const controller = new AbortController()
      inFlight.current = controller
      const ticket = ++sequence.current
      setEvaluating(true)

      quotesApi
        .evaluate(server.quoteId, toRequest(draft), controller.signal)
        .then((result) => {
          // A response for terms the user has already moved past is discarded.
          if (ticket !== sequence.current) return
          setLive(result)
          setEvaluationError(null)
        })
        .catch((error) => {
          if (controller.signal.aborted || ticket !== sequence.current) return
          // A validation failure here is information, not a crash: the previous
          // figures stay on screen and the message says what the server refused.
          setEvaluationError(error instanceof ApiError ? error : error)
        })
        .finally(() => {
          if (ticket === sequence.current) setEvaluating(false)
        })
    }, EVALUATION_DEBOUNCE_MS)

    return () => window.clearTimeout(timer)
  }, [draft, dirty, server.quoteId])

  useEffect(() => () => inFlight.current?.abort(), [])

  /* ------------------------------------------------------------ mutators */
  const setLines = useCallback((update: (lines: DraftLine[]) => DraftLine[]) => {
    setDraft((current) => ({ ...current, lines: update(current.lines) }))
  }, [])

  const setOrderDiscountBp = useCallback((bp: number | null) => {
    setDraft((current) => ({ ...current, orderDiscountBp: bp }))
  }, [])

  const setBackorderTerms = useCallback((terms: BackorderTerms) => {
    setDraft((current) => ({ ...current, backorderTerms: terms }))
  }, [])

  const setRequestedActivationDate = useCallback((date: string | null) => {
    setDraft((current) => ({ ...current, requestedActivationDate: date }))
  }, [])

  const reset = useCallback(() => {
    setDraft(draftFrom(server))
    baseline.current = draftFrom(server)
    baselineRevision.current = server.revisionId
    setLive(null)
    setEvaluationError(null)
    setExternalChange(null)
  }, [server])

  const acceptExternal = useCallback(() => {
    if (!externalChange) return
    baselineRevision.current = externalChange.revisionId
    baseline.current = draftFrom(externalChange)
    setDraft(draftFrom(externalChange))
    setLive(null)
    setExternalChange(null)
  }, [externalChange])

  const dismissExternal = useCallback(() => setExternalChange(null), [])

  const saveRequest = useCallback(
    () => toRequest(draft, server.rowVersion),
    [draft, server.rowVersion],
  )

  return {
    draft,
    // While there are unsaved edits the live evaluation is the truth on screen;
    // otherwise the saved server version is.
    evaluation: dirty && live ? live : server,
    dirty,
    evaluating,
    evaluationError,
    externalChange,
    setLines,
    setOrderDiscountBp,
    setBackorderTerms,
    setRequestedActivationDate,
    reset,
    acceptExternal,
    dismissExternal,
    saveRequest,
  }
}

/** A key for a line the user just added, before the server assigns one. */
export function newLineKey(): string {
  return `new-${Math.random().toString(36).slice(2, 10)}`
}
